"""Write switch/leasedesk.template.yaml: the whole LeaseDesk setup as one Switch template.

    uv run python scripts/build_template.py        # or: make template

The template is generated so the agent briefs live once, in switch/briefs/. Room instructions,
roles and the how-to-ask document live here. tests/switch/test_template.py fails when the
committed file differs from what this script writes, and checks it against the Part 4 brief.

Template language: version 2 of the installed server (switch-core 0.31.0, get_template_guide).
It has no `packages:` on rooms, so the leasedesk-governance package is attached after the run:
scripts/gateway.py package-attach (docs/DECISIONS.md, Part 4).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "switch" / "leasedesk.template.yaml"
BRIEFS = ROOT / "switch" / "briefs"

# A free OpenCode Zen model, from `opencode models opencode` on the day of the run.
SKEPTIC_MODEL = "opencode/big-pickle"
NAME_PATTERN = "^[a-z0-9][a-z0-9._-]*$"

HEADER = """\
# LeaseDesk: just-in-time AWS access, leased from chat.
# Generated by scripts/build_template.py from switch/briefs/; do not edit by hand (make template).
#
# Before running it: `make register` (keymaster and sentinel must exist) and OpenCode 1.x on
# the machine (Console's installer: npm install -g --prefix ~/.local opencode-ai@1; Switch
# 0.40 can't start OpenCode 2.x). Free Zen models need no sign-in. After it:
# scripts/gateway.py package-attach --room <access-desk> --room <security-review>, then
# `make doctor`.
"""

ACCESS_INSTRUCTIONS = """\
This room grants temporary AWS access through LeaseDesk. Ask @{scribe.name} in plain English. \
{scribe.name} drafts a lease, keymaster tracks it, @reviewer (sentinel and {skeptic.name}) \
reviews it, and a named person approves it. Access expires on its own.
- Every instruction must name an agent; follow-ups are off.
- Each lease gets its own thread; reply in the thread you were asked in.
- Only keymaster changes AWS. Only people listed in the access-policy can approve, and never \
their own request.
- access-policy and resource-catalog are written by people; agents read them and never edit \
them.
- Agents keep replies short and say plainly when something failed.
"""

REVIEW_INSTRUCTIONS = """\
High-risk leases from access-desk are escalated here. A HIGH lease needs approval from someone \
in the security group, given in this room. In an emergency, @keymaster freeze revokes every \
active lease and blocks new ones until @keymaster unfreeze.
"""

HOW_TO_ASK = """\
1. Mention @{scribe.name} and say what you need and why, in plain words. One request per thread.
2. {scribe.name} drafts a lease; keymaster posts it with an id. If it's yours, reply: \
@keymaster confirm LS-0001
3. sentinel reviews it; {skeptic.name} may add a note for the approver.
4. Someone on the access-policy approvers list approves it (never you). HIGH risk goes to \
security-review.
5. Access starts when approved and ends on its own. @keymaster revoke LS-0001 ends it early.

Example: "@{scribe.name} I need to read the October invoice exports in the billing bucket for \
an hour to debug the billing report (BILL-142)."
"""

KICKOFF = (
    "@{scribe.name} take the drafter role in this room, then introduce yourself in two lines. "
    "@{skeptic.name} take the reviewer role in this room, then introduce yourself in one line."
)

DRAFTER = {
    "name": "drafter",
    "exclusive": True,
    "instructions": "Draft lease proposals as the scribe brief says. "
    "Never approve or execute anything.",
}
REVIEWER = {
    "name": "reviewer",
    "exclusive": False,
    "instructions": "Review the lease in the thread you are mentioned in. Never approve.",
}
EXECUTOR = {
    "name": "executor",
    "exclusive": True,
    "instructions": "You are the only agent that changes AWS. "
    "Obey only the keymaster command grammar.",
}


def _brief(name: str) -> str:
    return (BRIEFS / f"{name}.md").read_text().strip() + "\n"


def _name_param(agent: str, what: str) -> dict[str, Any]:
    return {
        "type": "string",
        "label": f"{agent}'s name",
        "description": f"The {what} agent's name (lowercase letters, digits, . - _)",
        "default": agent,
        "pattern": NAME_PATTERN,
        "input": "advanced",
    }


def _agent(key: str, display: str, description: str, **fields: Any) -> dict[str, Any]:
    return {
        "type": "agent",
        "name": f"{{{key}_name}}",
        "display_name": display,
        "description": description,
        **fields,
        "machine": "{machine}",
        "directory": f"{{$agents_dir}}/{{{key}.name}}",
        "addressing": "anyone",
        "allow_existing": True,
        "instructions": _brief(key),
    }


def document() -> dict[str, Any]:
    return {
        "version": 2,
        "params": {
            "bridge": {
                "type": "bridge",
                "label": "Messaging app",
                "description": "Where the two rooms are created",
                "default": ["LeaseDesk Demo", "Discord", "Mattermost", "$first"],
            },
            "machine": {
                "type": "machine",
                "label": "Machine",
                "description": "The computer that runs scribe and skeptic",
                "default": ["$first"],
                "input": "advanced",
            },
            "scribe_name": _name_param("scribe", "drafter"),
            "skeptic_name": _name_param("skeptic", "red-team reviewer"),
            "skeptic_model": {
                "type": "string",
                "label": "skeptic's model",
                "description": "A free OpenCode Zen model (opencode models opencode)",
                "default": SKEPTIC_MODEL,
                "input": "advanced",
            },
        },
        "resources": {
            "scribe": _agent(
                "scribe",
                "Scribe",
                "Drafts least-privilege AWS lease proposals from plain-English requests",
                provider="claude",
                model="sonnet",
                advanced_config={
                    "effort": "low",
                    "disallowedTools": [
                        "Bash",
                        "Write",
                        "Edit",
                        "NotebookEdit",
                        "WebFetch",
                        "WebSearch",
                    ],
                },
            ),
            "skeptic": _agent(
                "skeptic",
                "Skeptic",
                "Red-team note on each lease for the approver; advisory, on a free model",
                provider="opencode",
                model="{skeptic_model}",
                advanced_config={"smallModel": "{skeptic_model}", "webSearch": "false"},
            ),
            "desk": {
                "type": "group",
                "name": "LeaseDesk",
                "description": "Just-in-time AWS access, leased from chat",
                "links": [{"from": "access", "to": "review", "label": "escalation"}],
            },
            "access": {
                "type": "room",
                "group": "desk",
                "name": "access-desk",
                "description": "Ask for temporary AWS access in plain English",
                "bridge": "{bridge}",
                "channel_type": "channel_public",
                "instructions": ACCESS_INSTRUCTIONS,
                "agents": ["scribe", "skeptic", "keymaster", "sentinel"],
                "users": ["{$creator}"],
                "roles": [DRAFTER, REVIEWER, EXECUTOR],
                "docs": [
                    {
                        "name": "how-to-ask",
                        "description": "How to ask for AWS access in this room",
                        "instructions": "Point anyone who asks how to get access here.",
                        "content": HOW_TO_ASK,
                    }
                ],
                "kickoff": KICKOFF,
            },
            "review": {
                "type": "room",
                "group": "desk",
                "name": "security-review",
                "description": "High-risk leases escalated from access-desk, approved by security",
                "bridge": "{bridge}",
                "channel_type": "channel_private",
                "instructions": REVIEW_INSTRUCTIONS,
                "agents": ["keymaster", "sentinel"],
                "users": ["{$creator}"],
                # No roles here: an agent holds one role lease across all rooms, and
                # keymaster and sentinel need theirs in access-desk.
            },
        },
        "form": {"advanced": {"label": "Advanced", "open": False}},
    }


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str)


def render() -> str:
    body = yaml.dump(
        document(),
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        width=1000,
        default_flow_style=False,
    )
    return HEADER + body


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)} ({len(render())} bytes)")


if __name__ == "__main__":
    main()
